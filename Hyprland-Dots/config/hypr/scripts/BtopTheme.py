#!/usr/bin/env python3
"""btop in the wallpaper's colours, laid out the way omarchy themes btop.

Run after every `wallust run` (WallustSwww.sh, WallpaperEffects.sh). wallust
writes the palette to ~/.config/btop/themes/wallust-palette.json (template
btop-palette.json); this turns it into ~/.config/btop/themes/wallust.theme -
the theme btop.conf's color_theme = "wallust" picks - and makes a running btop
reload it (SIGUSR2).

The layout is omarchy's btop.theme.tpl (omacom/omarchy, MIT): every box in a
hue of its own (cpu magenta, mem green, net red, proc the accent) and the
meters and graphs running across hues (cpu cyan -> blue -> magenta, temperature
green -> yellow -> red). Omarchy picks those hues by hand per theme; a
wallpaper palette rarely has them - a green wallpaper gives greens only - so
the six hues are real ones (red, yellow, green, cyan, blue, magenta) at the
lightness and saturation of the palette's vivid colours, each tinted at most
12 degrees toward a palette colour near it. Different on every wallpaper, but
never two boxes in the same colour.

The text is mixed most of the way to white: the palette's foreground is a
pale tint of the wallpaper, which read as grey-green in btop's tables.

The process list is in the wallpaper's own colour: btop draws the program
names, Threads and MemB along process_start -> process_end by value (and fades
them down the list with proc_gradient). Omarchy runs that ramp cyan -> blue ->
magenta, which put odd blue and magenta numbers in the table; here it runs from
wallust's accent (color7, the bar cards' lit colour and the proc box frame)
lifted halfway to the text colour, down to the plain accent.
The background stays empty, so btop sits on the terminal's own translucency.
"""
import colorsys
import json
import os
import subprocess
import sys

THEMES = os.path.expanduser("~/.config/btop/themes")
PALETTE = os.path.join(THEMES, "wallust-palette.json")
OUT = os.path.join(THEMES, "wallust.theme")

TEMPLATE = """\
# btop in the wallpaper's colours, omarchy's layout - GENERATED by
# ~/.config/hypr/scripts/BtopTheme.py on every wallpaper change; edit that.
theme[main_bg]=""
theme[main_fg]="{foreground}"
theme[title]="{foreground}"
theme[hi_fg]="{accent}"
theme[selected_bg]="{selection}"
theme[selected_fg]="{accent}"
theme[inactive_fg]="{muted}"
theme[graph_text]="{light_foreground}"
theme[meter_bg]="{selection}"
theme[proc_misc]="{light_foreground}"
theme[cpu_box]="{magenta}"
theme[mem_box]="{green}"
theme[net_box]="{red}"
theme[proc_box]="{accent}"
theme[div_line]="{muted}"
theme[temp_start]="{green}"
theme[temp_mid]="{yellow}"
theme[temp_end]="{red}"
theme[cpu_start]="{cyan}"
theme[cpu_mid]="{blue}"
theme[cpu_end]="{magenta}"
theme[free_start]="{magenta}"
theme[free_mid]="{blue}"
theme[free_end]="{cyan}"
theme[cached_start]="{blue}"
theme[cached_mid]="{cyan}"
theme[cached_end]="{magenta}"
theme[available_start]="{yellow}"
theme[available_mid]="{red}"
theme[available_end]="{red}"
theme[used_start]="{green}"
theme[used_mid]="{cyan}"
theme[used_end]="{blue}"
theme[download_start]="{yellow}"
theme[download_mid]="{red}"
theme[download_end]="{red}"
theme[upload_start]="{green}"
theme[upload_mid]="{cyan}"
theme[upload_end]="{blue}"
theme[process_start]="{process_start}"
theme[process_mid]="{process_mid}"
theme[process_end]="{accent}"
theme[gradient_color_0]="{background}"
theme[gradient_color_1]="{lighter_background}"
theme[gradient_color_2]="{selection}"
theme[gradient_color_3]="{muted}"
theme[gradient_color_4]="{dark_foreground}"
theme[gradient_color_5]="{foreground}"
theme[gradient_color_6]="{light_foreground}"
theme[gradient_color_7]="{bright_foreground}"
"""

# Where each hue sits on the colour wheel, in degrees.
HUES = {"red": 2, "yellow": 45, "green": 125, "cyan": 180, "blue": 215, "magenta": 300}


def rgb(h):
    return tuple(int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))


def hexc(r, g, b):
    return "#%02X%02X%02X" % tuple(round(max(0.0, min(1.0, v)) * 255) for v in (r, g, b))


def mix(a, b, t):
    return hexc(*(x + (y - x) * t for x, y in zip(rgb(a), rgb(b))))


def hls(h):
    return colorsys.rgb_to_hls(*rgb(h))


def build(pal):
    bg, fg = pal["background"], pal["foreground"]
    vivid = [hls(pal[f"color{i}"]) for i in range(1, 16)]
    vivid = [v for v in vivid if v[2] >= 0.3]
    light = sorted(v[1] for v in vivid)[len(vivid) // 2] if vivid else 0.62
    sat = sorted(v[2] for v in vivid)[len(vivid) // 2] if vivid else 0.60
    light = max(0.58, min(0.70, light))
    sat = max(0.50, min(0.75, sat))

    c = {
        "background": bg,
        "lighter_background": mix(bg, fg, 0.08),
        "selection": mix(bg, fg, 0.20),
        "muted": mix(bg, fg, 0.38),
        "dark_foreground": mix(bg, fg, 0.60),
        "foreground": mix(fg, "#FFFFFF", 0.65),
        "light_foreground": mix(fg, "#FFFFFF", 0.75),
        "bright_foreground": mix(fg, "#FFFFFF", 0.90),
        "accent": pal["color7"],
    }
    for name, h0 in HUES.items():
        best = None
        for i in range(1, 16):
            hh, _, ss = hls(pal[f"color{i}"])
            d = (hh * 360 - h0 + 180) % 360 - 180
            if ss >= 0.3 and abs(d) <= 25 and (best is None or abs(d) < abs(best)):
                best = d
        h = h0 + (max(-12, min(12, best)) if best is not None else 0)
        c[name] = hexc(*colorsys.hls_to_rgb((h % 360) / 360, light, sat))
    c["process_start"] = mix(c["accent"], c["light_foreground"], 0.45)
    c["process_mid"] = mix(c["accent"], c["light_foreground"], 0.22)
    return c


def main():
    try:
        with open(PALETTE, encoding="utf-8") as fh:
            pal = json.load(fh)
        theme = TEMPLATE.format(**build(pal))
    except (OSError, ValueError, KeyError) as err:
        print(f"BtopTheme.py: no usable palette ({err}) - btop theme left as it was", file=sys.stderr)
        return 0
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(theme)
    os.replace(tmp, OUT)
    # A running btop reloads its config and theme on SIGUSR2.
    subprocess.run(["pkill", "-USR2", "-x", "btop"], check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
